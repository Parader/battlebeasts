/** Raw recipe access — for effects that need to tweak a single layer before spawning. */
export function elementRoleLayers(
  element: ElementId,
  role: ElementRole,
): readonly Layer[] {
  return PRESETS[element][role];
}

/**
 * Live handle over one element role's emitters.
 *
 * Methods are bound to preallocated arrays, so driving these every frame costs no
 * allocations. `setRateScale` multiplies each layer's authored rate, which keeps the
 * mix between core/sparks/mist intact while a spell fades in or out.
 */
export type ElementHandle = {
  readonly ids: readonly number[];
  /** Move all layers; authored per-layer direction is preserved. */
  setPose(x: number, y: number, z: number): void;
  /** Move all layers and rotate authored directions so +Z means `yaw` forward. */
  setPoseYaw(x: number, y: number, z: number, yaw: number): void;
  /** Multiply every layer's authored rate (0 silences, 1 restores). */
  setRateScale(scale: number): void;
  kill(): void;
};

const NOOP_HANDLE: ElementHandle = {
  ids: [],
  setPose: () => {},
  setPoseYaw: () => {},
  setRateScale: () => {},
  kill: () => {},
};

/**
 * Spawn one element role at a world point.
 *
 * `overrides` is applied to every layer, so it is the right place for things that are
 * true of the whole effect (`duration`, a global `rate` gate, a color retint) and the
 * wrong place for per-layer tuning — use `elementRoleLayers` and `spawnEmitter` for that.
 */
export function spawnElementRole(
  element: ElementId,
  role: ElementRole,
  x: number,
  y: number,
  z: number,
  overrides?: Partial<EmitterSpawn>,
): ElementHandle {
  const layers = PRESETS[element][role];
  const ids: number[] = [];
  const baseRates: number[] = [];
  const dirX: number[] = [];
  const dirY: number[] = [];
  const dirZ: number[] = [];

  for (const layer of layers) {
    const cfg: EmitterSpawn = { ...BASE, ...layer, ...overrides, x, y, z };
    const id = spawnEmitter(cfg);
    if (id < 0) continue;
    ids.push(id);
    baseRates.push(cfg.rate ?? 0);
    dirX.push(cfg.dirX ?? 0);
    dirY.push(cfg.dirY ?? 0);
    dirZ.push(cfg.dirZ ?? 0);
  }
  if (ids.length === 0) return NOOP_HANDLE;

  return {
    ids,
    setPose(px, py, pz) {
      for (let i = 0; i < ids.length; i++) {
        setEmitterPose(ids[i]!, px, py, pz, dirX[i], dirY[i], dirZ[i]);
      }
    },
    setPoseYaw(px, py, pz, yaw) {
      const s = Math.sin(yaw);
      const c = Math.cos(yaw);
      for (let i = 0; i < ids.length; i++) {
        const dx = dirX[i]!;
        const dz = dirZ[i]!;
        setEmitterPose(ids[i]!, px, py, pz, dx * c + dz * s, dirY[i], -dx * s + dz * c);
      }
    },
    setRateScale(scale) {
      for (let i = 0; i < ids.length; i++) {
        setEmitterRate(ids[i]!, baseRates[i]! * scale);
      }
    },
    kill() {
      for (const id of ids) killEmitter(id);
      ids.length = 0;
    },
  };
}

/** One-shot burst: spawns the role, lets its burst fire, then self-expires. */
export function burstElementRole(
  element: ElementId,
  role: ElementRole,
  x: number,
  y: number,
  z: number,
  overrides?: Partial<EmitterSpawn>,
): void {
  spawnElementRole(element, role, x, y, z, { duration: 0.05, ...overrides });
}
