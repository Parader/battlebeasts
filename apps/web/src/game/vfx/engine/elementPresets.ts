/**
 * Per-element emitter recipes split by the role they play in a spell beat.
 *
 * The gallery in `elementGallery.ts` proves an element reads as itself standing still;
 * these are the same layering method (Ardent Wilds core + sparks + mist) retuned for
 * the four places a spell actually needs particles. Spell files compose roles instead
 * of hand-authoring emitter configs, so an element stays consistent across abilities
 * and a retune lands everywhere at once.
 */
export type ElementRole =
  /** Caster tell at the hand — tight, bright, short-lived. */
  | "cast"
  /** Projectile / stream wake — cheap, trail-ranked, no mist. */
  | "trail"
  /** Landing on a body — the loud beat, bursts on spawn. */
  | "impact"
  /** Lingering surface at y≈0 — zone identity, must survive seconds. */
  | "ground";

/** Layer recipe: everything except where it lives in the world. */
type Layer = Omit<EmitterSpawn, "x" | "y" | "z">;

