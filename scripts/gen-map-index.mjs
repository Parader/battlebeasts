/**
 * Generates the authored-map index from `packages/shared/src/maps/*.map.json`.
 *
 * A generated module rather than a runtime directory scan because the two
 * consumers resolve files completely differently: Vite bundles the client, and
 * the server runs from `dist`. A static list of imports is the one thing both
 * understand, and it keeps map documents out of any glob-plugin territory.
 *
 * Run `pnpm gen:maps` after saving a new map in the editor.
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MAPS_DIR = path.join(REPO_ROOT, "packages", "shared", "src", "maps");
const OUT = path.join(MAPS_DIR, "authored.generated.ts");

/** Map ids become identifiers, so they must be boring. Mirrors the editor API. */
const SAFE_ID = /^[a-z0-9][a-z0-9_-]{0,63}$/;

const HEADER = `// AUTO-GENERATED by scripts/gen-map-index.mjs -- do not edit.
// Run \`pnpm gen:maps\` after adding or renaming a map document.
`;

async function main() {
  const entries = await fs.readdir(MAPS_DIR).catch(() => []);
  const ids = entries
    .filter((f) => f.endsWith(".map.json"))
    .map((f) => f.slice(0, -".map.json".length))
    .filter((id) => {
      if (SAFE_ID.test(id)) return true;
      console.warn(`skipping "${id}.map.json": id must match ${SAFE_ID}`);
      return false;
    })
    .sort();

  const imports = ids
    .map((id) => `import ${ident(id)} from "./${id}.map.json";`)
    .join("\n");

  const registrations = ids.map((id) => `  register(${JSON.stringify(id)}, ${ident(id)});`).join("\n");

  const body = `${HEADER}
import { parseMapDoc } from "./mapDoc";
import { registerMapDoc } from "./registry";
${imports ? `\n${imports}\n` : ""}
/**
 * A document that fails to parse is skipped rather than thrown: one bad map
 * should not stop the server booting or take the whole client down, and the
 * warning names the file to fix.
 */
function register(id: string, raw: unknown): void {
  const { doc, errors } = parseMapDoc(raw);
  if (!doc) {
    console.error(\`[maps] "\${id}" failed to parse and was skipped\`, errors);
    return;
  }
  if (errors.length) console.warn(\`[maps] "\${id}" loaded with issues\`, errors);
  registerMapDoc(doc);
}

/**
 * Registers every editor-authored map. Called once at startup by the server
 * and the client; safe to call twice, since registration is keyed by map id.
 */
export function registerAuthoredMaps(): void {
${registrations || "  // No authored maps yet -- save one from the editor and run `pnpm gen:maps`."}
}

/** Ids of the authored maps compiled into this build. */
export const AUTHORED_MAP_IDS: readonly string[] = [${ids.map((i) => JSON.stringify(i)).join(", ")}];
`;

  await fs.writeFile(OUT, body, "utf8");
  console.log(`wrote ${path.relative(REPO_ROOT, OUT)} (${ids.length} map${ids.length === 1 ? "" : "s"})`);
  for (const id of ids) console.log(`  · ${id}`);
}

/** `test_arena` -> `doc_test_arena`, so a leading digit or dash can't break it. */
function ident(id) {
  return `doc_${id.replace(/-/g, "_")}`;
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
